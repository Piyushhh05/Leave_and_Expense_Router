def fmt(value):
    """How a Python value is written into a CSV cell."""
    if value is None:
        return ""
    if value is True:
        return "1"
    if value is False:
        return "0"
    if isinstance(value, date):
        return value.isoformat()
    return str(value)


def write_csv(path, columns, rows):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(columns)
        for row in rows:
            writer.writerow([fmt(row.get(c)) for c in columns])


def read_csv(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def file_sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


def sql_literal(value):
    """One value as a SQL literal. Empty cell -> NULL. Quotes doubled (works in MySQL)."""
    if value == "" or value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def write_seed_sql(path, tables_in_order, columns_by_table, rows_by_table, batch=200):
    """Writes INSERT statements for every table, parents first."""
    with open(path, "w", encoding="utf-8") as f:
        f.write("-- Seed data generated by generator/generate_data.py\n")
        f.write("-- Run sql/schema.sql first, then this file.\n\n")
        for table in tables_in_order:
            cols = columns_by_table[table]
            rows = rows_by_table[table]
            f.write(f"-- {table}: {len(rows)} rows\n")
            for i in range(0, len(rows), batch):
                chunk = rows[i:i + batch]
                f.write(f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n")
                lines = []
                for row in chunk:
                    values = ", ".join(sql_literal(fmt(row.get(c))) for c in cols)
                    lines.append(f"  ({values})")
                f.write(",\n".join(lines) + ";\n")
            f.write("\n")
