def holiday_dates(holidays, country):
    """Set of dates that are public holidays for one country."""
    return {h["holiday_date"] for h in holidays if h["country"] == country}


def count_days(start, end, holidays):
    """
    Returns (calendar_days, business_days).
    Business days = Monday-Friday that are not public holidays (inclusive range).
    """
    calendar_days = (end - start).days + 1
    business_days = 0
    day = start
    while day <= end:
        if day.weekday() < 5 and day not in holidays:   # 0-4 = Mon-Fri
            business_days += 1
        day += timedelta(days=1)
    return calendar_days, business_days


def random_date(rng, first, last):
    """A random date between first and last (both included)."""
    return first + timedelta(days=rng.randint(0, (last - first).days))


def next_weekday(day):
    """If day is Saturday or Sunday move forward to Monday."""
    while day.weekday() >= 5:
        day += timedelta(days=1)
    return day


def ranges_overlap(start_a, end_a, start_b, end_b):
    return start_a <= end_b and start_b <= end_a


