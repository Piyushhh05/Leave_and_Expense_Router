# IDs. All counters are zero padded and are never reused.
# ---------------------------------------------------------------------------
def emp_id(n):
    return f"EMP-{n:06d}"            # EMP-000001

def leave_id(n):
    return f"LVE-{C.YEAR}-{n:06d}"   # LVE-2026-000001

def claim_id(n):
    return f"EXP-{C.YEAR}-{n:06d}"   # EXP-2026-000001

def line_id(claim, line_no):
    return f"EXPL-{claim}-{line_no:02d}"   # EXPL-EXP-2026-000001-01

def step_id(request, step_no):
    return f"APR-{request}-{step_no:02d}"  # APR-EXP-2026-000001-01

def reimbursement_id(n):
    return f"RMB-{C.YEAR}-{n:06d}"   # RMB-2026-000001

def balance_id(n):
    return f"LBAL-{C.YEAR}-{n:06d}"

def event_id(n):
    return f"EVT-{n:06d}"


